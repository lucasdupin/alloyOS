/// Renders an 8x8 glyph at `(x, y)` in `fg` color with anti-aliased edge tinting,
/// and marks the 8x8 bounding box dirty in `fb`.
pub fn draw_char(fb: &mut MercuryFramebuffer, x: u32, y: u32, c: char, fg: u32) -> DirtyRect {
    draw_char_styled(fb, x, y, c, fg, false, true)
}

/// Renders an 8x8 glyph with configurable bold weight and anti-aliased liquid
/// silver edge tinting.
pub fn draw_char_styled(
    fb: &mut MercuryFramebuffer,
    x: u32,
    y: u32,
    c: char,
    fg: u32,
    bold: bool,
    anti_alias: bool,
) -> DirtyRect {
    let rows = glyph_bitmap(c);

    for (ry, &bits) in rows.iter().enumerate() {
        let effective_bits = if bold { bits | (bits >> 1) } else { bits };
        for rx in 0..8u32 {
            let mask = 0x80u8 >> rx;
            let px = x + rx;
            let py = y + (ry as u32);
            if (effective_bits & mask) != 0 {
                fb.put_pixel_raw(px, py, fg);
            } else if anti_alias {
                // Subpixel/edge anti-alias tinting when adjacent to active stroke pixels
                let has_left = rx > 0 && (effective_bits & (0x80u8 >> (rx - 1))) != 0;
                let has_right = rx < 7 && (effective_bits & (0x80u8 >> (rx + 1))) != 0;
                let has_up = ry > 0 && (rows[ry - 1] & mask) != 0;
                let has_down = ry < 7 && (rows[ry + 1] & mask) != 0;
                let neighbors =
                    (has_left as u8) + (has_right as u8) + (has_up as u8) + (has_down as u8);
                if neighbors >= 2 {
                    fb.put_pixel_blended_raw(px, py, ACCENT_LIQUID_SILVER, 72);
                }
            }
        }
    }

    let rect = DirtyRect::new(x, y, 8, 8);
    fb.mark_dirty(rect);
    rect
}

/// Renders a single-line or multi-line string in 8x8 monospace font.
pub fn draw_str(fb: &mut MercuryFramebuffer, x: u32, y: u32, text: &str, fg: u32) -> DirtyRect {
    draw_str_styled(fb, x, y, text, fg, false)
}

/// Renders a string with optional bold weight.
pub fn draw_str_styled(
    fb: &mut MercuryFramebuffer,
    x: u32,
    y: u32,
    text: &str,
    fg: u32,
    bold: bool,
) -> DirtyRect {
    let mut cx = x;
    let mut cy = y;
    let mut total_dirty = DirtyRect::new(x, y, 0, 0);

    for ch in text.chars() {
        if ch == '\n' {
            cx = x;
            cy += CHAR_LINE_HEIGHT;
            continue;
        }
        let r = draw_char_styled(fb, cx, cy, ch, fg, bold, true);
        total_dirty = rect_union(total_dirty, r);
        cx += CHAR_ADVANCE_X;
    }

    total_dirty
}

/// Renders a smooth liquid-mercury block cursor at `(x, y)`.
pub fn draw_cursor(fb: &mut MercuryFramebuffer, x: u32, y: u32, active: bool) -> DirtyRect {
    let rect = DirtyRect::new(x, y, 7, 8);
    if active {
        fb.fill_rect(x, y, 7, 8, TEXT_MERCURY_BRIGHT);
        fb.draw_rect_border(x, y, 7, 8, 1, ACCENT_LIQUID_SILVER);
    } else {
        fb.draw_rect_border(x, y, 7, 8, 1, BORDER_SILVER_DIM);
    }
    rect
}

/// Renders formatted Markdown & code blocks (`**bold**`, `` `code` ``, and fenced
/// ` ``` ` blocks) within a scrollback viewport `(scroll_offset_lines, max_visible_lines)`.
pub fn draw_markdown(
    fb: &mut MercuryFramebuffer,
    x: u32,
    y: u32,
    max_width: u32,
    markdown: &str,
    scroll_offset_lines: usize,
    max_visible_lines: usize,
) -> DirtyRect {
    let mut dirty = DirtyRect::new(x, y, 0, 0);
    let mut in_code_fence = false;
    let mut visible_rendered = 0usize;

    for (line_idx, raw_line) in markdown.lines().enumerate() {
        let trimmed = raw_line.trim_start();
        if trimmed.starts_with("```") {
            in_code_fence = !in_code_fence;
            if line_idx >= scroll_offset_lines && visible_rendered < max_visible_lines {
                let line_y = y + (visible_rendered as u32) * CHAR_LINE_HEIGHT;
                if let Some(r) = fb.draw_horizontal_line(
                    x,
                    line_y + 4,
                    max_width.min(320),
                    BORDER_SILVER_DIM,
                ) {
                    dirty = rect_union(dirty, r);
                }
                visible_rendered += 1;
            }
            continue;
        }

        if line_idx < scroll_offset_lines {
            continue;
        }
        if visible_rendered >= max_visible_lines {
            break;
        }

        let line_y = y + (visible_rendered as u32) * CHAR_LINE_HEIGHT;
        if in_code_fence {
            // Fenced code block row: carbon background fill + left silver accent bar + monospace text
            let box_w = max_width.max(64);
            if let Some(bg_rect) = fb.fill_rect(x, line_y, box_w, CHAR_LINE_HEIGHT, SURFACE_CARBON)
            {
                dirty = rect_union(dirty, bg_rect);
            }
            if let Some(bar_rect) =
                fb.fill_rect(x, line_y, 2, CHAR_LINE_HEIGHT, ACCENT_LIQUID_SILVER)
            {
                dirty = rect_union(dirty, bar_rect);
            }
            let text_rect = draw_str(fb, x + 6, line_y + 1, raw_line, ACCENT_LIQUID_SILVER);
            dirty = rect_union(dirty, text_rect);
        } else {
            let line_rect = draw_inline_markdown_line(fb, x, line_y, raw_line);
            dirty = rect_union(dirty, line_rect);
        }

        visible_rendered += 1;
    }

    dirty
}

/// Renders a single line containing `**bold**` and `` `code` `` inline spans.
fn draw_inline_markdown_line(
    fb: &mut MercuryFramebuffer,
    x: u32,
    y: u32,
    line: &str,
) -> DirtyRect {
    let mut cx = x;
    let mut dirty = DirtyRect::new(x, y, 0, 0);
    let bytes = line.as_bytes();
    let mut i = 0usize;
    let mut bold = false;
    let mut inline_code = false;

    while i < bytes.len() {
        if !inline_code && i + 1 < bytes.len() && bytes[i] == b'*' && bytes[i + 1] == b'*' {
            bold = !bold;
            i += 2;
            continue;
        }
        if bytes[i] == b'`' {
            inline_code = !inline_code;
            i += 1;
            continue;
        }

        let ch = bytes[i] as char;
        if inline_code {
            if let Some(bg) = fb.fill_rect(cx, y, CHAR_ADVANCE_X, CHAR_LINE_HEIGHT - 1, SURFACE_CARBON) {
                dirty = rect_union(dirty, bg);
            }
            let r = draw_char_styled(fb, cx, y, ch, ACCENT_LIQUID_SILVER, false, true);
            dirty = rect_union(dirty, r);
        } else {
            let r = draw_char_styled(fb, cx, y, ch, TEXT_MERCURY_BRIGHT, bold, true);
            dirty = rect_union(dirty, r);
        }
        cx += CHAR_ADVANCE_X;
        i += 1;
    }

    dirty
}
